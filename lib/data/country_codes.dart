/// Dial-code data for the country picker (ISO 3166-1 alpha-2 + E.164 code).
///
/// [length] is the typical national significant number length; when omitted,
/// [maxDigits] falls back to the E.164 cap of 15 digits including the
/// country code.
class CountryCode {
  const CountryCode(this.name, this.iso, this.dial, [this.length]);

  final String name;
  final String iso;
  final String dial;
  final int? length;

  /// Design default: India +91, 10 digits.
  static const CountryCode india = CountryCode('India', 'IN', '+91', 10);

  bool get isIndia => iso == 'IN';

  /// Flag emoji derived from the ISO code's regional indicator symbols.
  String get flag => String.fromCharCodes(
    iso.codeUnits.map((unit) => 0x1F1E6 + (unit - 0x41)),
  );

  /// Maximum national digits accepted for this dial code.
  int get maxDigits => length ?? (16 - dial.length);
}

