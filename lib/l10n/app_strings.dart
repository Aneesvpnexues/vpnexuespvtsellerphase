import 'package:flutter/widgets.dart';

/// In-app translation table.
///
/// Keys are the English source strings themselves, so a call site that has no
/// translation yet keeps rendering the English text (the lookup falls back to
/// the key). Migrate a screen by wrapping its strings in
/// `AppStrings.trOf(context, '...')` and adding entries to [_tables] for the
/// languages that need them.
///
/// The widget is installed once by `MaterialApp.builder` in `main.dart`, so
/// every route — pushed on top of the app's navigator — sits below it.
