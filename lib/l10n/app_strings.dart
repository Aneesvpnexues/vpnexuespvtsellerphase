  const AppStrings({
    super.key,
    required this.languageCode,
    required super.child,
  });

  /// The active two-letter language code (from `LocaleService`).
  final String languageCode;

  /// Translates [key] for this scope's language.
  String tr(String key) => translate(languageCode, key);

  /// Look up [key] for [languageCode]; returns [key] itself when no table
  /// entry exists (English source text doubles as the fallback).
  static String translate(String languageCode, String key) =>
      _tables[languageCode]?[key] ?? key;

  /// Build-method helper: reads the nearest [AppStrings] scope, or falls back
  /// to English when the tree has none (widget tests pump bare `MaterialApp`s).
  static String trOf(BuildContext context, String key) {
    final AppStrings? scope =
        context.dependOnInheritedWidgetOfExactType<AppStrings>();
    return scope?.tr(key) ?? key;
  }

