-- Public seller product catalog used by the no-login seller app.
-- Targets the existing public.sellers_products table (plural).
-- Safe to run more than once in the Supabase SQL Editor.

create table if not exists public.sellers_products (
  id bigint generated by default as identity primary key,
  product_name text not null,
  category text not null,
  price numeric(12, 2) not null default 0,
  quantity integer not null default 0,
  product_img_1 text,
  product_img_2 text,
  product_img_3 text,
  product_img_4 text,
  product_img_5 text,
  product_descrption text not null default ''
);

-- Upgrade the existing table in place without dropping any columns.
alter table public.sellers_products
  add column if not exists product_img_1 text,
  add column if not exists product_img_2 text,
  add column if not exists product_img_3 text,
  add column if not exists product_img_4 text,
  add column if not exists product_img_5 text,
  add column if not exists product_descrption text not null default '';

create index if not exists sellers_products_category_idx
  on public.sellers_products (category);

alter table public.sellers_products enable row level security;

drop policy if exists sellers_products_public_read on public.sellers_products;

create policy sellers_products_public_read on public.sellers_products
for select to anon, authenticated
using (true);

revoke insert, update, delete on table public.sellers_products
  from anon, authenticated;

grant select on table public.sellers_products to anon, authenticated;
grant all on table public.sellers_products to service_role;

-- Copy the public product catalog into the seller catalog once.
insert into public.sellers_products (
  product_name,
  category,
  price,
  quantity,
  product_img_1,
  product_img_2,
  product_img_3,
  product_img_4,
  product_img_5,
  product_descrption
)
select
  trim(p.name),
  case lower(trim(p.category))
    when 'fruits' then 'fruits'
    when 'grains' then 'grains & pulses'
    when 'grains and pulses' then 'grains & pulses'
    when 'grains & pulses' then 'grains & pulses'
    else 'vegetables'
  end,
  greatest(coalesce(p.current_price, 0), 0),
  greatest(coalesce(p.quantity, 0), 0),
  nullif(trim(p.image_urls[1]), ''),
  nullif(trim(p.image_urls[2]), ''),
  nullif(trim(p.image_urls[3]), ''),
  nullif(trim(p.image_urls[4]), ''),
  nullif(trim(p.image_urls[5]), ''),
  coalesce(p.description, '')
from public.products p
where nullif(trim(p.name), '') is not null
  and not exists (
    select 1
    from public.sellers_products sp
    where lower(sp.product_name) = lower(trim(p.name))
  );

notify pgrst, 'reload schema';
